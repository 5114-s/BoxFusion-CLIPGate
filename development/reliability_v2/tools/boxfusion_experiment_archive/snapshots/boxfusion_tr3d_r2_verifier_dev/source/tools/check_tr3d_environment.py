#!/usr/bin/env python3
"""Read-only health check for the pinned official TR3D runtime."""

from __future__ import annotations

import argparse
import importlib
import json
import os
import subprocess
import sys
import tempfile
import traceback
from pathlib import Path
from typing import Any, Dict, Optional, Sequence, Tuple


PIN = "fe25f7a51d36e3702f961e198894580d83c4387b"
TR3D_TREE = "e7d4f3eaaeb39473babf52ef47af0d81fe72d6c8"
VERSION_RANGES = {
    "mmcv": ("2.0.0rc4", "2.2.0"),
    "mmdet": ("3.0.0", "3.3.0"),
    "mmengine": ("0.7.1", "1.0.0"),
}
ABI_PINS = {
    "numpy": "1.23.5",
    "numba": "0.56.4",
    "llvmlite": "0.39.1",
}
SUPPORTED_HEADS = {"TR3DHead", "TR3DClassAgnosticHead"}


def _version_tuple(value: str) -> Tuple[Tuple[int, ...], int]:
    """Return a comparison key supporting the rc spellings used here."""
    value = value.split("+", 1)[0]
    if "rc" in value:
        release, rc = value.split("rc", 1)
        stage = -1000 + int(rc)
    else:
        release, stage = value, 0
    nums = tuple(int(piece) for piece in release.split(".") if piece.isdigit())
    return nums, stage


def _in_range(value: str, lower: str, upper: str) -> bool:
    return _version_tuple(lower) <= _version_tuple(value) < _version_tuple(
        upper
    )


def _git(root: Path, *args: str) -> str:
    return subprocess.check_output(
        ["git", "-C", os.fspath(root), *args],
        stderr=subprocess.STDOUT,
        text=True,
    ).strip()


def _module_record(name: str) -> Dict[str, Any]:
    record: Dict[str, Any] = {"ok": False}
    try:
        module = importlib.import_module(name)
        record.update(
            ok=True,
            version=getattr(module, "__version__", None),
            path=getattr(module, "__file__", None),
        )
    except Exception as exc:  # health checker must report every dependency
        record.update(
            error=f"{type(exc).__name__}: {exc}",
            traceback=traceback.format_exc(limit=3),
        )
    return record


def _load_source_config(config: Path, vendor: Path) -> Tuple[Any, str]:
    """Load the official config without requiring an editable installation.

    MMEngine's scoped `mmdet3d::` syntax resolves through `mmdet3d/.mim`,
    which is generated by pip/mim rather than tracked by upstream git. The
    fallback rewrites only those base paths in temporary config files. It does
    not change config values or the pinned vendor checkout.
    """
    from mmengine.config import Config

    try:
        return Config.fromfile(os.fspath(config)), "installed_scope"
    except FileNotFoundError as exc:
        if "mmdet3d/.mim" not in str(exc):
            raise

    common_source = vendor / "projects" / "TR3D" / "configs" / "tr3d.py"
    runtime_source = vendor / "configs" / "_base_" / "default_runtime.py"
    dataset_source = (
        vendor / "configs" / "_base_" / "datasets" / "scannet-3d.py"
    )
    with tempfile.TemporaryDirectory(prefix="boxfusion-tr3d-config-") as tmp:
        tmp_root = Path(tmp)
        common_target = tmp_root / "tr3d.py"
        common_text = common_source.read_text(encoding="utf-8")
        common_text = common_text.replace(
            "'mmdet3d::_base_/default_runtime.py'",
            repr(os.fspath(runtime_source)),
        )
        common_text = common_text.replace(
            "'../../../configs/_base_/default_runtime.py'",
            repr(os.fspath(runtime_source)),
        )
        common_target.write_text(common_text, encoding="utf-8")

        scan_target = tmp_root / config.name
        scan_text = config.read_text(encoding="utf-8")
        scan_text = scan_text.replace(
            "'./tr3d.py'", repr(os.fspath(common_target))
        )
        scan_text = scan_text.replace(
            "'mmdet3d::_base_/datasets/scannet-3d.py'",
            repr(os.fspath(dataset_source)),
        )
        scan_target.write_text(scan_text, encoding="utf-8")
        return Config.fromfile(os.fspath(scan_target)), "source_temp_paths"


def check(
    root: Path,
    config: Path,
    build_model: bool,
    check_dataset_sample: bool,
    require_cuda: bool,
) -> Tuple[Dict[str, Any], bool]:
    vendor = root / "third_party" / "mmdetection3d"
    result: Dict[str, Any] = {
        "schema": "boxfusion.tr3d_environment_check.v1",
        "ok": False,
        "python": {
            "executable": sys.executable,
            "version": sys.version,
            "prefix": sys.prefix,
        },
        "vendor": {"path": os.fspath(vendor)},
        "config": {"path": os.fspath(config)},
        "modules": {},
        "checks": {},
    }
    ok = True

    try:
        commit = _git(vendor, "rev-parse", "HEAD")
        tree = _git(vendor, "rev-parse", "HEAD:projects/TR3D")
        status_lines = _git(
            vendor, "status", "--porcelain", "--untracked-files=all"
        ).splitlines()
        unexpected = [
            line
            for line in status_lines
            if not line.startswith("?? mmdet3d/.mim/")
            and not line.startswith("?? mmdet3d.egg-info/")
        ]
        dirty = bool(unexpected)
        result["vendor"].update(
            commit=commit,
            tr3d_tree=tree,
            dirty=dirty,
            ignored_generated_paths=len(status_lines) - len(unexpected),
        )
        vendor_ok = commit == PIN and tree == TR3D_TREE and not dirty
    except Exception as exc:
        result["vendor"]["error"] = f"{type(exc).__name__}: {exc}"
        vendor_ok = False
    result["checks"]["vendor_pin"] = vendor_ok
    ok &= vendor_ok

    vendor_text = os.fspath(vendor)
    root_text = os.fspath(root)
    for source_path in (vendor_text, root_text):
        while source_path in sys.path:
            sys.path.remove(source_path)
    sys.path.insert(0, root_text)
    sys.path.insert(0, vendor_text)
    os.chdir(root)

    for name in (
        "torch",
        "mmengine",
        "mmcv",
        "mmdet",
        "mmdet3d",
        "MinkowskiEngine",
        "numpy",
        "numba",
        "llvmlite",
    ):
        result["modules"][name] = _module_record(name)
        ok &= bool(result["modules"][name]["ok"])

    for name, (lower, upper) in VERSION_RANGES.items():
        value = result["modules"][name].get("version")
        compatible = bool(value) and _in_range(str(value), lower, upper)
        result["checks"][f"{name}_version"] = {
            "ok": compatible,
            "found": value,
            "required": f">={lower},<{upper}",
        }
        ok &= compatible

    for name, required in ABI_PINS.items():
        value = result["modules"][name].get("version")
        compatible = value == required
        result["checks"][f"{name}_abi_version"] = {
            "ok": compatible,
            "found": value,
            "required": f"=={required}",
        }
        ok &= compatible

    numba_abi_ok = False
    try:
        internal = importlib.import_module("numba.np.ufunc._internal")
        result["checks"]["numba_numpy_abi"] = {
            "ok": True,
            "path": getattr(internal, "__file__", None),
        }
        numba_abi_ok = True
    except Exception as exc:
        result["checks"]["numba_numpy_abi"] = {
            "ok": False,
            "error": f"{type(exc).__name__}: {exc}",
            "traceback": traceback.format_exc(limit=5),
        }
    ok &= numba_abi_ok

    torch_record = result["modules"]["torch"]
    if torch_record["ok"]:
        torch = sys.modules["torch"]
        cuda_available = bool(torch.cuda.is_available())
        torch_record["cuda_available"] = cuda_available
        torch_record["cuda_runtime"] = torch.version.cuda
        if cuda_available:
            torch_record["device"] = torch.cuda.get_device_name(0)
        result["checks"]["cuda"] = {
            "ok": cuda_available or not require_cuda,
            "required": require_cuda,
        }
        ok &= cuda_available or not require_cuda
    else:
        result["checks"]["cuda"] = {"ok": False, "required": require_cuda}
        ok = False

    config_ok = False
    try:
        cfg, load_mode = _load_source_config(config, vendor)
        head_type = cfg.model.bbox_head.get("type")
        result["config"].update(
            loaded=True,
            load_mode=load_mode,
            model_type=cfg.model.get("type"),
            backbone_type=cfg.model.backbone.get("type"),
            head_type=head_type,
            class_agnostic=head_type == "TR3DClassAgnosticHead",
        )
        config_ok = (
            cfg.model.get("type") == "MinkSingleStage3DDetector"
            and cfg.model.backbone.get("type") == "TR3DMinkResNet"
            and head_type in SUPPORTED_HEADS
        )
    except Exception as exc:
        result["config"].update(
            loaded=False,
            error=f"{type(exc).__name__}: {exc}",
            traceback=traceback.format_exc(limit=5),
        )
        cfg = None
    result["checks"]["config_load"] = config_ok
    ok &= config_ok

    project_ok = False
    try:
        project = importlib.import_module("projects.TR3D.tr3d")
        project_path = Path(project.__file__).resolve()
        expected_root = (vendor / "projects" / "TR3D").resolve()
        project_ok = expected_root in project_path.parents
        result["checks"]["project_import"] = {
            "ok": project_ok,
            "path": os.fspath(project_path),
        }
    except Exception as exc:
        result["checks"]["project_import"] = {
            "ok": False,
            "error": f"{type(exc).__name__}: {exc}",
            "traceback": traceback.format_exc(limit=5),
        }
    ok &= project_ok

    if build_model:
        model_ok = False
        try:
            if cfg is None:
                raise RuntimeError("config did not load")
            from mmdet3d.registry import MODELS
            from mmdet3d.utils import register_all_modules

            register_all_modules(init_default_scope=True)
            model = MODELS.build(cfg.model)
            parameter_count = sum(p.numel() for p in model.parameters())
            model_class = type(model).__name__
            backbone_class = type(model.backbone).__name__
            head = model.bbox_head
            head_class = type(head).__name__
            head_contract: Dict[str, Any] = {
                "class": head_class,
                "supported": head_class in SUPPORTED_HEADS,
            }
            if head_class == "TR3DClassAgnosticHead":
                label2level = tuple(head.label2level)
                out_channels = int(head.conv_cls.out_channels)
                head_contract.update(
                    label2level=list(label2level),
                    out_channels=out_channels,
                    class_agnostic_ok=(
                        label2level == (0, ) and out_channels == 1
                    ),
                )
            else:
                head_contract["class_agnostic_ok"] = None
            model_ok = (
                model_class == "MinkSingleStage3DDetector"
                and backbone_class == "TR3DMinkResNet"
                and bool(head_contract["supported"])
                and head_contract.get("class_agnostic_ok") is not False
            )
            result["checks"]["model_build"] = {
                "ok": model_ok,
                "class": model_class,
                "backbone_class": backbone_class,
                "head": head_contract,
                "parameters": parameter_count,
            }
        except Exception as exc:
            result["checks"]["model_build"] = {
                "ok": False,
                "error": f"{type(exc).__name__}: {exc}",
                "traceback": traceback.format_exc(limit=8),
            }
        ok &= model_ok
    else:
        result["checks"]["model_build"] = {
            "ok": None,
            "skipped": True,
            "hint": "pass --build-model",
        }

    if check_dataset_sample:
        dataset_ok = False
        try:
            if cfg is None:
                raise RuntimeError("config did not load")
            from mmdet3d.registry import DATASETS
            from mmdet3d.utils import register_all_modules

            register_all_modules(init_default_scope=True)
            dataset = DATASETS.build(cfg.train_dataloader.dataset)
            sample = dataset[0]
            points = sample["inputs"]["points"]
            instances = sample["data_samples"].gt_instances_3d
            boxes = instances.bboxes_3d.tensor
            labels = instances.labels_3d
            labels_unique = sorted(set(int(v) for v in labels.tolist()))
            class_agnostic = (
                cfg.model.bbox_head.get("type")
                == "TR3DClassAgnosticHead"
            )
            dataset_ok = (
                len(dataset) > 0
                and points.ndim == 2
                and points.shape[1] >= 3
                and bool(points.isfinite().all())
                and boxes.ndim == 2
                and boxes.shape[1] >= 6
                and bool(boxes.isfinite().all())
                and (not class_agnostic or labels_unique in ([], [0]))
            )
            result["checks"]["dataset_sample"] = {
                "ok": dataset_ok,
                "class": type(dataset).__name__,
                "length": len(dataset),
                "points_shape": list(points.shape),
                "boxes_shape": list(boxes.shape),
                "labels_unique": labels_unique,
            }
        except Exception as exc:
            result["checks"]["dataset_sample"] = {
                "ok": False,
                "error": f"{type(exc).__name__}: {exc}",
                "traceback": traceback.format_exc(limit=8),
            }
        ok &= dataset_ok
    else:
        result["checks"]["dataset_sample"] = {
            "ok": None,
            "skipped": True,
            "hint": "pass --check-dataset-sample",
        }

    result["ok"] = bool(ok)
    return result, bool(ok)


def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    default_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=default_root)
    parser.add_argument("--config", type=Path)
    parser.add_argument("--build-model", action="store_true")
    parser.add_argument("--check-dataset-sample", action="store_true")
    parser.add_argument("--require-cuda", action="store_true")
    parser.add_argument(
        "--report-only",
        action="store_true",
        help="Print failures but exit zero; useful for auditing a foreign env.",
    )
    return parser.parse_args(argv)


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    root = args.root.resolve()
    config = args.config
    if config is None:
        config = (
            root
            / "third_party"
            / "mmdetection3d"
            / "projects"
            / "TR3D"
            / "configs"
            / "tr3d_1xb16_scannet-3d-18class.py"
        )
    result, ok = check(
        root=root,
        config=config.resolve(),
        build_model=args.build_model,
        check_dataset_sample=args.check_dataset_sample,
        require_cuda=args.require_cuda,
    )
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0 if ok or args.report_only else 1


if __name__ == "__main__":
    raise SystemExit(main())
